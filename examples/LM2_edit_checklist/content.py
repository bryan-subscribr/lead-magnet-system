# ================= CHECKLIST STEPS =================
h1('Step 1: Cut Everything That Doesn\'t Earn The Next Line')
para("The first pass is pure cutting. Questions, restarts, ums, the warm-up before a good answer, and any answer he gave twice. Only the better version stays.")
para("The rule we use is the same one I use on scripts. If the first sentence doesn't get you to the second sentence, it gets cut. For every line, ask: can this go without making the video weaker? If yes, it goes.")
para("**Tell your editor:** \"Cut anything that doesn't make me want to hear the next line. If I said it twice, keep the better one.\"")

h1('Step 2: Tighten It, But Keep It Human')
para("Next, the editor tightens the gaps between sentences. Most raw footage drags, so a lot of silence comes out.")
para("But not all of it. Cut every single breath and you sound like a robot. The test we use: listen back without watching the screen. If you get bored, it's too slow. If you can't keep up, it's too fast.")
para("Easy parts can move quickly. When he's explaining something hard, the edit slows down and gives it room.")
para("**Tell your editor:** \"Tighten the gaps, but leave enough breathing room that I still sound like a person.\"")

h1('Step 3: Open With The Best Line, Then The Title')
para("Nobody starts a Chamath video with \"Hey guys, welcome back\". The video opens on his strongest lines from the whole interview, laid over slow, moody B-roll with the words on screen. B-roll just means any footage that isn't him talking to camera.")
para("Then the title card hits. Only after that does the video go back to him in the chair.")
img('cold_open.jpg', 6.5, caption='(The first 30 seconds of his top video.)')
para("The opening has one job: prove the viewer clicked on the right video. If the title promises 30 years of business advice, the first thing they hear should be some of that advice.")
para("**Tell your editor:** \"Find my 3 best lines from the whole recording and open with them over B-roll. Then the title card.\"")

h1('Step 4: Put A Name On Screen')
para("Early in the video, his name and who he is appear on screen, small and clean. A new viewer might not know who he is, and this answers \"why should I listen to this guy?\" without him having to say it.")
img('lower_third.jpg', 6.5, caption='(His name and title, in the first minute.)')
para("For a business, this is free credibility. Your name and one line of proof, like how many clients you've helped or the result you're known for, goes on screen while you talk.")
para("**Tell your editor:** \"Add my name and one line about me in the first minute.\"")

h1('Step 5: Change What\'s On Screen Every Few Sentences')
para("Here's the rule that holds people the longest: something on screen changes every 2 or 3 sentences. A switch to the other camera, a text card, a chart, a slow push in. Leave a talking head untouched for 20 seconds and people start scrolling.")
para("This is what the first 60 seconds of his top video looks like, one frame every 4 seconds:")
img('first_60.jpg', 6.5, caption='(Wide, close, quote card, title, chapter card, name. Barely two frames in a row look the same.)')
para("Notice what's missing. No flashing emojis, no spinning zooms, no meme sound effects. Every change is calm and it all looks expensive. Simple graphics that back up the words beat flashy ones that fight them.")
para("**Tell your editor:** \"Change something on screen every 2 to 3 sentences. Keep it clean, nothing flashy.\"")

h1('Step 6: Split It Into Chapters')
para("Long videos get split into chapters, and each one starts with its own full-screen title card. It tells the viewer \"new section, here's what it's about\", which pulls back anyone whose mind wandered.")
img('chapters.jpg', 6.5, caption='(Each chapter gets its own card.)')
para("**Tell your editor:** \"Give every main point its own chapter card.\"")

h1('Step 7: Give The Big Ideas Their Own Card')
para("When he says something people will want to remember, the screen goes dark and the line appears on its own. It's the edit's way of saying \"write this down\".")
img('text_cards.jpg', 6.5, caption='(One idea, one card.)')
para("This is also what people screenshot and share. Keep these short. If it doesn't fit on one line, it's too long for a card.")
para("**Tell your editor:** \"Every time I say a one-liner people should remember, put it on its own card.\"")

h1('Step 8: Every Number Goes On Screen')
para("If he says a number, you see the number. When he talks about compound interest, a table builds year by year. When he mentions November 2021, it lands on a chart. When he compares two people, you see two lines.")
img('charts.jpg', 6.5, caption='(Numbers are hard to hear and easy to see.)')
para("For a business owner, this is your biggest edge. Your client results, your prices, your before and after numbers, all of it should be on screen. Nobody remembers \"we grew their revenue a lot\". They remember the chart.")
para("**Tell your editor:** \"Every number I say goes on screen. If I compare two things, show them side by side.\"")

h1('Step 9: Music Under Every Word')
para("Music is the biggest upgrade for the least effort. It sets the mood before anyone notices a single cut.")
para("On every video we edit, the music comes up during the opening and the chapter cards, then drops right down whenever someone's talking. His voice always wins. Small sound effects, like a soft whoosh, come in when a card or chart appears, so nothing just pops up in silence. Silent pop-ups look cheap.")
img('music_levels.jpg', 6.5, caption='(Loud between the words. Quiet under them.)')
para("**Tell your editor:** \"Music up for the intro and chapter cards, down under my voice. A soft sound whenever something appears on screen.\"")

h1('Step 10: One Final Watch, Then Export')
para("Before it goes live, someone watches the whole thing once, start to finish, at normal speed, on a phone. Most of your viewers watch on a phone, so that's where it has to work. Anything that drags gets cut, even this late.")
para("Then it's exported at the volume level YouTube expects, so you're not quieter or louder than every other video in someone's feed. Your editor will know this as -14 LUFS. You don't need to know what that means. Just ask for it.")
para("**Tell your editor:** \"Export at YouTube loudness, -14 LUFS. And send it to me once, finished, not in pieces.\"")

