# ================= 3.6 ANALYTICS =================
h1('Analytics: Find What\'s Broken, Starting From The Money', stat='Scott: ~$40,000/mo from YouTube')
para("If you don't make money from your channel, it's very hard to justify making YouTube videos. Read the numbers from the money backward and fix the lowest step that's broken.")
flow([('1', 'Revenue + calls'), ('2', 'Link clicks'), ('3', 'Right viewers'), ('4', 'The video'), ('5', 'Production')], name='p3_flow_ladder.png')
table([['Step', 'What I check', 'Rule'],
       ['Revenue and calls', 'Every booked call traced back to the video it came from', 'Set up tracking first'],
       ['Link clicks', 'Clicks and calls per video', 'Count clicks and calls per video'],
       ['Right viewers', 'Returning viewers', 'Subscribers are a vanity metric'],
       ['The video', 'Views after 30 days, first 30 seconds of retention', 'Little to no link between higher AVD and views'],
       ['Production', 'Recording, editing, thumbnails', 'Whatever stops you posting consistently']],
      [1.4, 2.8, 2.3])

h3('The 2 Numbers I Check On A Video')
bullets(["Views after 30 days. Too early to judge before then, unless the view chart flatlines.",
         "Retention in the first 30 seconds. It shows the strength of your hook.",
         "CTR: aim for 5%. At 1 to 2%, work on it. When a video spreads to a colder audience, CTR and retention go down, and that doesn't mean the packaging is bad."])

h3('Judge Each Video Against What You Expected')
img('p3_gpt5_card.jpg', 4.5)
para("A scriptwriting video of mine averages about 2,000 views. The GPT-5 video was a broader idea and I expected 5,000. It got about 2,000. The idea was hot for 2 days, my editors weren't ready, and we posted late. The variables to check: the title, the thumbnail, the script, or just the idea.")
para("Testing: thumbnail first, then the title.")

